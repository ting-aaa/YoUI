using System.Diagnostics;
using System.Numerics;
using System.Runtime.InteropServices;
using YoUI;
using YoUI.Platform.Windows;

internal static class NativeMouseLeaveTests
{
    internal static void Run()
    {
        if (!OperatingSystem.IsWindows()) throw new PlatformNotSupportedException("Native mouse-leave acceptance requires an interactive Windows desktop.");
        if (!GetCursorPos(out var original)) throw new InvalidOperationException("Cannot read desktop cursor.");
        var root = new Element();
        var button = root.Add(new ProbeButton { Transform = RectTransform.Fixed(0, 0, 80, 60) });
        int clicks = 0; button.Clicked += () => clicks++;
        using var window = new DesktopWindow("YoUI native mouse-leave acceptance", root, 320, 200, 100, 100);
        Vector2? observedMove = null;
        int nativeLeaves = 0;
        void Observe(UiEvent e)
        {
            if (e.Kind != EventKind.PointerMove) return;
            observedMove = e.Position;
            if (e.Position == new Vector2(-1, -1)) nativeLeaves++;
        }
        window.Document.PreviewInput += Observe;
        try
        {
            // Keep the complete test window on the primary desktop and above other windows.
            Check(SetWindowPos(window.Handle, -1, 100, 100, 0, 0, 0x0041), "position/show test window");
            SetForegroundWindow(window.Handle);
            window.PumpEvents(); window.RenderNow();
            Point Client(int x, int y)
            {
                var p = new Point { X = (int)(x * window.Scale), Y = (int)(y * window.Scale) };
                Check(ClientToScreen(window.Handle, ref p), "convert client point"); return p;
            }
            void Move(int x, int y)
            {
                var p = Client(x, y); Check(SetCursorPos(p.X, p.Y), "move cursor");
            }
            void Until(Func<bool> predicate, string description)
            {
                var timeout = Stopwatch.StartNew();
                do { window.PumpEvents(); if (predicate()) return; Thread.Sleep(10); } while (timeout.Elapsed < TimeSpan.FromSeconds(3));
                GetCursorPos(out var actual);
                throw new Exception($"{description}; cursor={actual.X},{actual.Y}; observedMove={observedMove}; hover={button.IsHovered}; leaves={nativeLeaves}");
            }
            nint Position(int x, int y) => (nint)((ushort)(short)(x * window.Scale) | ((int)(ushort)(short)(y * window.Scale) << 16));
            // Two cursor changes without pumping do not establish OS exit/entry delivery.
            // First observe a real client move that arms tracking, then its real leave.
            int anchorX = 120, anchorY = 80;
            var anchor = Client(anchorX, anchorY);
            Check(GetCursorPos(out var current), "read startup cursor");
            if (current.X == anchor.X && current.Y == anchor.Y) { anchorX = 160; anchorY = 100; }
            var expectedAnchor = new Vector2((int)(anchorX * window.Scale) / window.Scale, (int)(anchorY * window.Scale) / window.Scale);
            Check(root.VisualBounds.Contains(expectedAnchor) && !button.VisualBounds.Contains(expectedAnchor), "startup anchor is inside the client and outside the button");
            Move(anchorX, anchorY);
            Until(() => observedMove == expectedAnchor, "native startup client move not delivered");
            int startupLeaves = nativeLeaves;
            Move(-20, 20);
            Until(() => nativeLeaves > startupLeaves && !button.IsHovered, "native startup leave not delivered");
            for (int cycle = 0; cycle < 3; cycle++)
            {
                Move(5, 20); Until(() => button.IsHovered, "native re-entry did not hover edge button");
                window.RenderNow();
                Move(-20, 20);
                Until(() => !button.IsHovered, "native WM_MOUSELEAVE did not clear hover");
                Check(window.Document.NeedsRender, "native leave requests repaint");
                window.RenderNow();
            }
            // The press/release messages are deterministic injections. Movement and leave
            // are generated by Windows from SetCursorPos, never by posting WM_MOUSELEAVE.
            Move(5, 20); Until(() => button.IsHovered, "hover before drag");
            SendMessage(window.Handle, 0x0201, 1, Position(5, 20)); window.PumpEvents();
            Check(GetCapture() == window.Handle, "host acquires native capture");
            int moves = button.Moves;
            Move(-20, 20);
            Until(() => button.Moves > moves && button.LastMove.X < 0, "captured native move outside missing");
            Check(button.Cancels == 0 && GetCapture() == window.Handle, "leave preserves capture");
            SendMessage(window.Handle, 0x0202, 0, Position(-20, 20)); window.PumpEvents();
            Check(button.Ups == 1 && clicks == 0 && GetCapture() != window.Handle, "outside release keeps original capture semantics");
            Check(button.SentinelMoves == 0, "leave never injects fake coordinates into captured drag");
            Move(5, 20); Until(() => button.IsHovered, "re-entry after capture");
            SendMessage(window.Handle, 0x0201, 1, Position(5, 20));
            SendMessage(window.Handle, 0x0202, 0, Position(5, 20)); window.PumpEvents();
            Check(clicks == 1, "fresh click still activates");
            Move(-20, 20); Until(() => !button.IsHovered, "leave tracking re-arms after capture");
            Console.WriteLine("PASS native Win32 mouse-leave: 3 edge exits/re-entries, captured outside movement/release, fresh click, post-capture leave. Press/release messages injected; leave/movement OS-generated.");
        }
        finally { window.Document.PreviewInput -= Observe; ReleaseCapture(); SetCursorPos(original.X, original.Y); }
    }

    private static void Check(bool value, string message) { if (!value) throw new Exception(message); }
    [StructLayout(LayoutKind.Sequential)] private struct Point { public int X, Y; }
    [DllImport("user32")] private static extern bool GetCursorPos(out Point point);
    [DllImport("user32")] private static extern bool SetCursorPos(int x, int y);
    [DllImport("user32")] private static extern bool ClientToScreen(nint hwnd, ref Point point);
    [DllImport("user32")] private static extern bool SetWindowPos(nint hwnd, nint after, int x, int y, int width, int height, uint flags);
    [DllImport("user32")] private static extern bool SetForegroundWindow(nint hwnd);
    [DllImport("user32")] private static extern nint GetCapture();
    [DllImport("user32")] private static extern bool ReleaseCapture();
    [DllImport("user32", CharSet = CharSet.Unicode)] private static extern nint SendMessage(nint hwnd, uint message, nuint wParam, nint lParam);
}
